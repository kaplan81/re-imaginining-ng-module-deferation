#!/usr/bin/env node
/**
 * Renders the deck under `docs/deck/` as one readable document, `docs/NARRATION.md`:
 * every slide's speaker notes, in order, under its title.
 *
 * Why this exists: speaker notes sit one click apart inside the deck. This puts
 * them in a single file you can read top to bottom, diff and quote from — and
 * because it is GENERATED from the slide files, it cannot drift away from what the
 * deck actually says.
 *
 * It is a reference and nothing more. There are deliberately no word counts and no
 * spoken-time estimates: the talk is improvised against the slides rather than read
 * off this file, so a number here would only invite pacing the deck by arithmetic.
 * See `docs/NG-POLAND-2026.md` §2, "On length".
 *
 * `docs/deck/` is the source of truth. Edit the slides there, publish from there,
 * and regenerate this afterwards. Never hand-edit `docs/NARRATION.md`: say what you
 * want changed and the change goes into the slide.
 *
 * Usage: node tools/deck-to-narration.mjs
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { JSDOM } from 'jsdom';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const deckDir = join(root, 'docs', 'deck', 'project');
const outPath = join(root, 'docs', 'NARRATION.md');

const index = JSON.parse(readFileSync(join(deckDir, 'deck.json'), 'utf8'));

/** Inline text of an element, with <br> as an em dash and whitespace collapsed. */
function text(el) {
  const clone = el.cloneNode(true);
  for (const br of clone.querySelectorAll('br'))
    br.replaceWith(clone.ownerDocument.createTextNode(' — '));
  return clone.textContent.replace(/\s+/g, ' ').trim();
}

// section id -> the slide it starts at
const sectionStart = new Map();
for (const [key, sec] of Object.entries(index.sections ?? {}))
  sectionStart.set(sec.start, { key, ...sec });

const slides = [];
for (const id of index.order) {
  const file = join(deckDir, 'slides', `${id}.html`);
  if (!existsSync(file)) {
    slides.push({ id, missing: true });
    continue;
  }
  const dom = new JSDOM(readFileSync(file, 'utf8'));
  const section = dom.window.document.querySelector('section');
  const aside = section?.querySelector(':scope > aside');
  const notes = aside
    ? aside.textContent
        .replace(/[ \t]+/g, ' ')
        .replace(/\n{3,}/g, '\n\n')
        .trim()
    : '';
  const heading = section?.querySelector('h1, h2, h3');
  slides.push({ id, title: heading ? text(heading) : '(no heading)', notes });
}

const L = [];
L.push(`# ${index.title} — speaker notes`);
L.push('');
L.push(
  `Generated by \`node tools/deck-to-narration.mjs\` from \`docs/deck/\`, which is the source of truth for the deck. ` +
    `**Do not hand-edit this file** — change the slide and regenerate.`,
);
L.push('');
L.push(
  `A reference, not a script. The talk is improvised against the slides, so there are no word counts and no timings here.`,
);
L.push('');
L.push(`**${slides.length} slides**`);
L.push('');
L.push('| # | Slide | Title |');
L.push('| --- | --- | --- |');
slides.forEach((s, i) => {
  L.push(`| ${i + 1} | \`${s.id}\` | ${s.missing ? '**MISSING FILE**' : s.title} |`);
});
L.push('');
L.push('---');
L.push('');

slides.forEach((s, i) => {
  const sec = sectionStart.get(s.id);
  if (sec) {
    L.push(`# ${sec.description}`);
    L.push('');
  }
  L.push(`## ${i + 1} · \`${s.id}\` — ${s.missing ? '**MISSING FILE**' : s.title}`);
  L.push('');
  if (s.missing) {
    L.push('> This slide is in `order` but has no file.');
    L.push('');
    return;
  }
  L.push(s.notes ? s.notes : '*(no speaker notes)*');
  L.push('');
  L.push('---');
  L.push('');
});

writeFileSync(outPath, L.join('\n'));
console.log(`docs/NARRATION.md — ${slides.length} slides`);
